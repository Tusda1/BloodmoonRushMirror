using UnityEngine;
using UnityEngine.Pool;
using VContainer;
using VContainer.Unity;

namespace Bat {
    public class BatPoolManager {
        #region ---Fields---
        private readonly IObjectResolver _container;
        public readonly ObjectPool<Bat> Pool;
        private readonly GameObject _batPrefab;
        private readonly int _initialBatPoolSize;
        private readonly Transform _batParentTransform;
        #endregion

        #region ---Initialization---
        [Inject]
        public BatPoolManager(IObjectResolver container, GameObject batPrefab,
            int initialBatPoolSize, Transform batParentTransform = null) {
            _container = container;

            Pool = CreateBatPool();
            _batPrefab = batPrefab;
            _initialBatPoolSize = initialBatPoolSize;
            _batParentTransform = batParentTransform
                                  ?? new GameObject("BatPoolParent - AutoGenerated").transform;
        }
        #endregion

        private ObjectPool<Bat> CreateBatPool() {
            var batPool = new ObjectPool<Bat>(
                CreateBat,
                ActionOnGet,
                ActionOnRelease,
                ActionOnDestroy,
                true,
                _initialBatPoolSize);

            var bats = new Bat[_initialBatPoolSize];
            for (var i = 0; i < _initialBatPoolSize; i++) {
                bats[i] = batPool.Get();
            }

            foreach (var bat in bats) {
                batPool.Release(bat);
            }

            return batPool;
        }

        #region ---ObjectPoolMethods---
        private void ActionOnDestroy(Bat bat) {
            Object.Destroy(bat.gameObject);
        }

        private void ActionOnRelease(Bat bat) {
            bat.gameObject.SetActive(false);
        }

        private void ActionOnGet(Bat bat) {
            bat.gameObject.SetActive(true);
            bat.currentHealth = bat.defaultHealth;
            bat.splineAnimate.Restart(true);
        }

        private Bat CreateBat() {
            var obj = _container.Instantiate(_batPrefab, _batParentTransform);
            obj.SetActive(false);
            return obj.GetComponent<Bat>();
        }
        #endregion
    }
}